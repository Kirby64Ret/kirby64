#!/bin/sh
# Serialised build. Several agents share one working tree, and two `make`
# processes writing the same object produced a genuinely corrupt .o last wave:
#   bad reloc symbol index (0x80805 >= 0x254) for offset 0x8080808
# which then looks like a decompilation defect and costs an hour to chase.
#
# Use this instead of calling make directly. It waits for the lock rather than
# failing, so a queued build just takes longer.
#
# Usage: tools/decomp/mk.sh [make args]     default: -j8
cd /home/user/kirby64_decomp || exit 1

# RE-SPLIT WHEN THE YAML IS NEWER THAN THE LINKER SCRIPT.
#
# build/kirby.ld is GENERATED by splat from kirby64.yaml, and nothing in the
# Makefile depends on it -- `split` is a separate manual target. So editing
# kirby64.yaml and running make links the new objects against the OLD layout,
# and the result is not subtly wrong, it is unrecognisable: a rodata migration
# left mid-flight this way produced a ROM differing from the base in 3,741
# regions and 30 MB, with 26 MB of that inside game_assets, because every
# segment after the changed one had moved. It reads exactly like catastrophic
# breakage by a decompilation lane and it is a stale file.
#
# It cost an hour tonight. One mtime comparison prevents it.
if [ kirby64.yaml -nt build/kirby.ld ] || [ ! -f build/kirby.ld ]; then
    echo "mk.sh: kirby64.yaml is newer than build/kirby.ld -- re-running splat"
    flock /tmp/kirby_build.lock uv run splat split kirby64.yaml || exit 1
fi

exec flock /tmp/kirby_build.lock make "${@:--j8}"
